"use client";
import { useEffect, useState } from "react";
import { api, type Organization } from "../../../lib/api/phase3";

type Record = {
  proposal_id: string;
  kind: "open" | "click";
  requests: number;
  first_seen_at: string | null;
  last_seen_at: string | null;
};
type Report = { disclaimer: string; records: Record[] };

export default function Phase6TrackingPage() {
  const [orgs, setOrgs] = useState<Organization[]>([]);
  const [org, setOrg] = useState("");
  const [report, setReport] = useState<Report | null>(null);
  const [error, setError] = useState("");
  useEffect(() => {
    let active = true;
    api<Organization[]>("/api/recruitment/organizations")
      .then((rows) => { if (active) { setOrgs(rows); if (rows.length) setOrg(rows[0].id); } })
      .catch((e: unknown) => { if (active) setError(String(e)); });
    return () => { active = false; };
  }, []);
  useEffect(() => {
    if (!org) return;
    let active = true;
    api<Report>(`/api/phase6/organizations/${encodeURIComponent(org)}/tracking`)
      .then((value) => { if (active) { setReport(value); setError(""); } })
      .catch((e: unknown) => { if (active) setError(String(e)); });
    return () => { active = false; };
  }, [org]);
  const totals = (report?.records ?? []).reduce((acc, r) => {
    acc[r.kind] += r.requests;
    return acc;
  }, { open: 0, click: 0 });
  return <main className="min-h-screen bg-[#fffaf1] px-5 py-8 text-stone-900">
    <div className="mx-auto max-w-6xl space-y-6">
      <a className="text-amber-800 underline" href="/phase6">Back to Phase 6</a>
      <h1 className="text-3xl font-bold">Email engagement signals</h1>
      <p className="text-stone-600">Privacy-aware SMTP email tracking. Requests are not proof a person read or clicked the email.</p>
      <label className="block text-sm font-semibold">Organization
        <select className="ml-3 rounded-lg border p-2" value={org} onChange={(e) => setOrg(e.target.value)}>
          {orgs.map((o) => <option key={o.id} value={o.id}>{o.name}</option>)}
        </select>
      </label>
      {error && <p role="alert" className="rounded-lg border border-red-300 bg-red-50 p-3">{error}</p>}
      <div className="grid gap-4 sm:grid-cols-2">
        <div className="rounded-xl border bg-white p-5"><p>Observed image requests</p><p className="text-3xl font-bold">{totals.open}</p></div>
        <div className="rounded-xl border bg-white p-5"><p>Observed tracked-link requests</p><p className="text-3xl font-bold">{totals.click}</p></div>
      </div>
      <div className="overflow-x-auto rounded-xl border bg-white p-4">
        <table className="w-full text-left text-sm"><thead><tr><th className="p-2">Proposal ID</th><th className="p-2">Signal</th><th className="p-2">Requests</th><th className="p-2">First seen</th></tr></thead>
          <tbody>{(report?.records ?? []).map((r) => <tr key={`${r.proposal_id}-${r.kind}`} className="border-t"><td className="p-2 font-mono text-xs">{r.proposal_id}</td><td className="p-2">{r.kind}</td><td className="p-2">{r.requests}</td><td className="p-2">{r.first_seen_at ? new Date(r.first_seen_at).toLocaleString() : "—"}</td></tr>)}</tbody>
        </table>
        {report?.records.length === 0 && <p className="p-2 text-stone-500">No tracking records yet. Tracking is off by default.</p>}
      </div>
      <p className="text-xs text-stone-500">Signals can be generated by image proxies or automated security scanners; never use them to rank or reject candidates.</p>
    </div>
  </main>;
}
